/* =====================================================================
   App shell: state, data loading, rendering, events.

   Two ways this gets real data (tried in order, each one a fallback for
   the last):
   1. GET /api/dashboard - the FastAPI backend (webapp/server.py), when
      it's actually running (local dev, or a VPS/always-on host).
   2. Static JSON files at data/<brand-slug>.json - pre-generated by
      scripts/export_static_site.py on a schedule (see
      .github/workflows/update-data.yml) and committed to the repo, so
      GitHub Pages (which can only serve static files, no server) can
      still show real, periodically-refreshed data with no backend at all.
   3. SAMPLE from data.js - if neither of the above is reachable.
   ===================================================================== */

import { SAMPLE } from './data.js';
import { nav } from './components/nav.js';
import { header, filters } from './components/header.js';
import { overviewPage } from './components/overview.js';
import { stockoutsPage } from './components/stockouts.js';
import { competitionPage } from './components/competition.js';
import { forecastPage } from './components/forecast.js';
import { alertsPage } from './components/alerts.js';
import { metadataPage } from './components/metadata.js';
import { storePanel } from './components/storePanel.js';

const API_URL = '/api/dashboard';

const params = new URLSearchParams(location.search);
const state = {
  page: params.get('page') || 'overview',   // overview | stock | competition | forecast | alerts
  brand: params.get('brand') || null,       // null = whatever the backend's default primary brand is
  alertType: 'All',
  productBrand: 'All',
  productStore: 'All',
  productView: 'latest',
  productSearch: '',
  store: params.has('store') ? Number(params.get('store')) : -1,  // index into data.stores, -1 = panel closed
  theme: readTheme(),
  busy: false
};
let data = SAMPLE;
let isLive = false;  // true once a real /api/dashboard response has loaded

function readTheme() {
  try { return localStorage.getItem('shelf-pulse-theme') || 'light'; } catch { return 'light'; }
}
function saveTheme(t) {
  try { localStorage.setItem('shelf-pulse-theme', t); } catch { /* private mode */ }
}

/** Must match the Python slugify in scripts/export_static_site.py exactly. */
function slugify(name) {
  return name.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '');
}

/** Try the live backend, then the static JSON snapshot, then the sample. */
async function loadData() {
  const q = new URLSearchParams();
  if (state.brand) q.set('brand', state.brand);
  try {
    const res = await fetch(`${API_URL}?${q}`, { headers: { Accept: 'application/json' } });
    if (!res.ok) throw new Error(res.status);
    data = await res.json();
    state.brand = data.brand.name;  // keep in sync with whatever the backend actually used
    isLive = true;
  } catch {
    try {
      let slug = state.brand ? slugify(state.brand) : null;
      if (!slug) {
        const idx = await (await fetch('data/index.json')).json();
        slug = idx.defaultSlug;
      }
      const res = await fetch(`data/${slug}.json`);
      if (!res.ok) throw new Error(res.status);
      data = await res.json();
      state.brand = data.brand.name;
      isLive = true;
    } catch {
      data = SAMPLE;  // neither a live backend nor a static snapshot is reachable
      isLive = false;
    }
  }
  render();
}

let toast = null;  // { text } - transient message shown under the header after a refresh

/** POST /api/refresh (triggers a real live Blinkit collector run), then reload. */
async function refreshLive() {
  state.busy = true; render();
  try {
    const res = await fetch('/api/refresh', { method: 'POST' });
    const { rows_collected, new_alerts } = await res.json();
    toast = { text: `Collected ${rows_collected} new row${rows_collected === 1 ? '' : 's'}, ${new_alerts} new alert${new_alerts === 1 ? '' : 's'} in Alerts.` };
  } catch {
    toast = { text: "Couldn't reach the backend - is `uvicorn server:app` running?" };
  }
  state.busy = false;
  await loadData();
  setTimeout(() => { toast = null; render(); }, 6000);
}

/** On-demand nearby-store check for one stock-out row (data.stockouts[index]).
    Not run automatically for every row - see server.py module docstring. */
async function checkNearby(index) {
  const row = data.stockouts[index];
  if (!row) return;
  row.nearby = { tone: 'neutral', text: 'Checking…' };
  render();
  try {
    const res = await fetch('/api/nearby', {
      method: 'POST', headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ product_id: row.productId, location_name: row.store, pincode: row.pincode || '' })
    });
    const { results } = await res.json();
    const best = results?.find(r => r.tone === 'ok') || results?.[0];
    row.nearby = best ? { tone: best.tone, text: best.text } : { tone: 'neutral', text: 'No nearby stores found' };
  } catch {
    row.nearby = { tone: 'neutral', text: 'Check failed - is the backend running?' };
  }
  render();
}

/** Download the current dashboard payload as JSON (client-side, no backend route needed). */
function exportData() {
  const blob = new Blob([JSON.stringify(data, null, 2)], { type: 'application/json' });
  const a = document.createElement('a');
  a.href = URL.createObjectURL(blob);
  a.download = `shelf-pulse-${data.brand.name.toLowerCase().replace(/\s+/g, '-')}-${state.page}.json`;
  a.click();
  URL.revokeObjectURL(a.href);
}

const PAGES = {
  overview: d => overviewPage(d),
  stock: d => stockoutsPage(d),
  competition: d => competitionPage(d),
  forecast: d => forecastPage(d),
  alerts: (d, s) => alertsPage(d, s),
  metadata: (d, s) => metadataPage(d, s)
};

function render() {
  document.documentElement.classList.toggle('dark', state.theme === 'dark');
  const root = document.getElementById('app');
  root.className = 'app';
  const footnote = isLive
    ? `${data.meta.platform} stock is read live from an unofficial source, for demo purposes. For real use we'd need a licensed data partner or an agreement with the platform.`
    : `Showing sample data - the backend (uvicorn server:app, in webapp/) isn't reachable right now.`;
  root.innerHTML = `
    ${nav(data, state)}
    <div class="main">
      ${header(data, state)}
      ${filters(data)}
      <main class="content">
        ${toast ? `<div class="fchip" style="display:inline-flex;margin-bottom:12px;background:var(--surface-2)">${toast.text}</div>` : ''}
        ${PAGES[state.page](data, state)}
        <p class="footnote">${footnote}</p>
      </main>
    </div>
    ${storePanel(data, state.store)}`;
}

/* One click handler for the whole app — elements declare data-action. */
document.addEventListener('click', e => {
  const el = e.target.closest('[data-action]');
  if (!el) return;
  const { action, page, store, index, value } = el.dataset;
  switch (action) {
    case 'go':            state.page = page; state.store = -1; window.scrollTo(0, 0); break;
    case 'open-store':    state.store = Number(store); break;
    case 'close-store':   state.store = -1; break;
    case 'refresh':       return refreshLive();
    case 'export':        return exportData();
    case 'check-nearby':  return checkNearby(Number(index));
    case 'alert-filter':  state.alertType = value; break;
    case 'product-filter': state.productBrand = value; break;
    case 'product-store-filter': state.productStore = value; break;
    case 'product-view':   state.productView = value; break;
    case 'toggle-theme':  state.theme = state.theme === 'dark' ? 'light' : 'dark'; saveTheme(state.theme); break;
    default: return;
  }
  render();
});

/* Input handler - the Metadata page's product search box. Filtered in the
   DOM directly (show/hide rows) instead of via state + re-render, so typing
   doesn't lose input focus on every keystroke. The query is still stored in
   state so it survives the Latest/History toggle and chip filters. */
document.addEventListener('input', e => {
  const el = e.target.closest('[data-action="product-search"]');
  if (!el) return;
  state.productSearch = el.value;
  const q = el.value.trim().toLowerCase();
  let visible = 0;
  document.querySelectorAll('#products-table .trow').forEach(r => {
    const show = !q || (r.dataset.search || '').includes(q);
    r.style.display = show ? '' : 'none';
    if (show) visible++;
  });
  const empty = document.getElementById('products-no-match');
  if (empty) {
    empty.style.display = visible ? 'none' : '';
    empty.textContent = `No rows match "${el.value.trim()}".`;
  }
});

/* Change handler - for the brand <select> in the left nav. */
document.addEventListener('change', e => {
  const el = e.target.closest('[data-action]');
  if (!el) return;
  if (el.dataset.action === 'brand') { state.brand = el.value; state.store = -1; return loadData(); }
});

/* Keyboard: Enter/Space on map pins, Escape closes the panel */
document.addEventListener('keydown', e => {
  if (e.key === 'Escape' && state.store >= 0) { state.store = -1; render(); }
  if ((e.key === 'Enter' || e.key === ' ') && e.target.matches?.('g[data-action="open-store"]')) {
    e.preventDefault(); state.store = Number(e.target.dataset.store); render();
  }
});

render();
loadData();
